from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass

import pandas as pd
from sqlalchemy import create_engine

from etl import config as cfg

SQL_PATH = cfg.ROOT / "analytics" / "queries.sql"
REPORT_PATH = cfg.REPORT_DIR / "kpi_report.md"

HEADER = re.compile(r"^--\s*QUERY\s+(\d+)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*$", re.MULTILINE)


@dataclass
class Query:
    number: int
    title: str
    techniques: str
    sql: str


def parse_queries(path=SQL_PATH) -> list[Query]:
    text = path.read_text(encoding="utf-8")
    matches = list(HEADER.finditer(text))
    queries: list[Query] = []

    for i, m in enumerate(matches):
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        block = text[start:end]

        stmt = block.split(";")[0].strip()
        if stmt:
            queries.append(Query(int(m.group(1)), m.group(2), m.group(3), stmt))

    return queries


def run(numbers: list[int] | None = None, write_report: bool = False) -> int:
    queries = parse_queries()
    if numbers:
        queries = [q for q in queries if q.number in numbers]

    engine = create_engine(cfg.mysql_url(), future=True)
    raw = engine.raw_connection()
    lines: list[str] = [
        "# SQL Analytics — KPI Report",
        "",
        "Generated by `python -m analytics.run_queries --report` against the live "
        "`ecommerce_dw` warehouse. Every figure reads through `vw_delivered_items`, "
        "so revenue is always *price + freight on delivered orders*.",
        "",
    ]
    failures = 0

    try:
        for q in queries:
            banner = f"QUERY {q.number:02d} · {q.title}"
            print(f"\n{'=' * 78}\n{banner}\n{'techniques: ' + q.techniques}\n{'=' * 78}")
            try:
                cur = raw.cursor()
                cur.execute(q.sql)
                rows = cur.fetchall()
                df = pd.DataFrame(rows, columns=[c[0] for c in cur.description])
                cur.close()
            except Exception as exc:
                failures += 1
                print(f"FAILED: {type(exc).__name__}: {str(exc)[:200]}")
                lines += [f"## {banner}", "", f"**FAILED** — `{str(exc)[:200]}`", ""]
                continue

            print(df.to_string(index=False))
            print(f"\n({len(df)} rows)")

            lines += [
                f"## {banner}",
                "",
                f"*Techniques: {q.techniques}*",
                "",
                df.to_markdown(index=False),
                "",
            ]
    finally:
        raw.close()
        engine.dispose()

    print(f"\n{'=' * 78}")
    print(f"{len(queries) - failures}/{len(queries)} queries succeeded")

    if write_report:
        REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")
        print(f"report written -> {REPORT_PATH}")

    return 1 if failures else 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Run the SQL analytics layer")
    ap.add_argument("numbers", nargs="*", type=int,
                    help="specific query numbers to run (default: all)")
    ap.add_argument("--report", action="store_true",
                    help="write docs/kpi_report.md")
    args = ap.parse_args()
    return run(args.numbers or None, args.report)


if __name__ == "__main__":
    sys.exit(main())
